"""Apply a validated plan: write pages, regenerate wiki/index.md, prepend to wiki/log.md, commit once."""

from __future__ import annotations

import datetime
import difflib
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath

from . import frontmatter, gitops
from .plan import WIKI, Plan, vault_files
from .vault import Vault, write_atomic, write_lock

__all__ = ["ApplyError", "ApplyResult", "apply_plan", "render_index"]

INDEX = f"{WIKI}/index.md"
LOG = f"{WIKI}/log.md"
INDEX_NOTE = "<!-- Generated by akashactl from page frontmatter. Edits here are overwritten. -->"


class ApplyError(Exception):
    pass


@dataclass
class ApplyResult:
    files: dict[str, tuple[str | None, str]] = field(default_factory=dict)  # path -> (old, new)
    log_entry: str = ""
    commit: str | None = None

    def summary_lines(self, diff: bool = False) -> list[str]:
        lines = []
        for path, (old, new) in self.files.items():
            if old is None:
                lines.append(f"create {path} ({len(new.splitlines())} lines)")
            elif old == new:
                continue
            else:
                added = removed = 0
                for line in difflib.ndiff(old.splitlines(), new.splitlines()):
                    added += line.startswith("+ ")
                    removed += line.startswith("- ")
                lines.append(f"update {path} (+{added} -{removed} lines)")
            if diff:
                lines.extend(
                    difflib.unified_diff(
                        (old or "").splitlines(), new.splitlines(), f"a/{path}", f"b/{path}", lineterm=""
                    )
                )
        return lines


def apply_plan(plan: Plan, vault: Vault, note_schema: dict, dry_run: bool = False,
               now: datetime.datetime | None = None) -> ApplyResult:
    now = now or datetime.datetime.now().astimezone()
    result = ApplyResult()
    for change in plan.pages:
        result.files[change.path] = (change.old_content, change.content)

    pending = {c.path: c.content for c in plan.pages}
    old_index = _read(vault.root / INDEX)
    new_index = render_index(vault, note_schema, pending)
    result.files[INDEX] = (old_index, new_index)

    old_log = _read(vault.root / LOG)
    result.log_entry = _log_entry(plan, now)
    result.files[LOG] = (old_log, _prepend_log(old_log or "", result.log_entry))

    if dry_run:
        return result

    for rel in (INDEX, LOG):
        target = vault.root / rel
        if target.is_symlink() or (target.parent.exists() and target.parent.is_symlink()):
            raise ApplyError(f"{rel} or its folder is a symlink; refusing to write")
    with write_lock(vault, plan.operation, list(result.files)):
        originals: dict[Path, bytes | None] = {}
        try:
            for rel, (_, new) in result.files.items():
                target = vault.root / rel
                originals[target] = target.read_bytes() if target.exists() else None
                target.parent.mkdir(parents=True, exist_ok=True)
                write_atomic(target, new.encode("utf-8"))
            result.commit = gitops.commit_paths(
                vault.root, list(result.files), f"akasha: {plan.operation}: {plan.log}", plan.operation,
                "\n".join(result.summary_lines()),
            )
        except BaseException:
            for target, data in originals.items():
                if data is None:
                    target.unlink(missing_ok=True)
                else:
                    write_atomic(target, data)
            raise
    return result


def render_index(vault: Vault, note_schema: dict, pending: dict[str, str] | None = None) -> str:
    """Catalog every generated, typed page under wiki/, grouped by type in schema order."""
    pending = pending or {}
    pages: dict[str, str] = {}
    for rel in vault_files(vault):
        if rel.startswith(f"{WIKI}/") and rel.endswith(".md"):
            pages[rel] = _read(vault.root / rel) or ""
    pages.update(pending)

    groups: dict[str, list[tuple[str, str]]] = {t: [] for t in note_schema["types"]}
    for rel, text in pages.items():
        try:
            meta, _ = frontmatter.parse(text)
        except frontmatter.FrontmatterError:
            continue
        if meta.get("generated") is not True or meta.get("type") not in groups:
            continue
        title = str(meta.get("title") or PurePosixPath(rel).stem).replace("|", "-").replace("]", ")")
        groups[meta["type"]].append((title, rel[: -len(".md")]))

    out = ["# Index", "", INDEX_NOTE]
    for tname, entries in groups.items():
        if not entries:
            continue
        label = note_schema["types"][tname].get("label", tname.capitalize())
        out += ["", f"## {label}", ""]
        out += [f"- [[{link}|{title}]]" for title, link in sorted(entries, key=lambda e: (e[0].lower(), e[1]))]
    return "\n".join(out) + "\n"


def _log_entry(plan: Plan, now: datetime.datetime) -> str:
    lines = [f"## {now:%Y-%m-%d %H:%M} · {plan.operation}", "", plan.log, ""]
    for change in plan.pages:
        verb = "created" if change.action == "create" else "updated"
        lines.append(f"- {verb} [[{change.path[: -len('.md')]}]]")
    return "\n".join(lines) + "\n"


def _prepend_log(old: str, entry: str) -> str:
    """Newest first: insert the entry right after the '# Log' heading."""
    if old.startswith("# Log"):
        head, _, rest = old.partition("\n")
        rest = rest.lstrip("\n")
        return f"{head}\n\n{entry}" + (f"\n{rest}" if rest else "")
    return f"# Log\n\n{entry}" + (f"\n{old}" if old.strip() else "")


def _read(path: Path) -> str | None:
    return path.read_text(encoding="utf-8") if path.is_file() else None

